// ТИПЫ СВЯЗЕЙ ПО КРАТНОСТИ:
// Одинарная: H2 (H-H), HCl (H-Cl), NH3 (N-H), H2O (O-H), CH4 (C-H)
// Двойная: O2 (O=O), CO2 (O=C=O), SO2, C2H4 (этилен)
