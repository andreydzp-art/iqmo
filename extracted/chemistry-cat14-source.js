// Браузерный режим: конвертируем и добавляем в общий банк.
(function () {
	if (typeof window === 'undefined') return;
	if (!Array.isArray(IQMO_CAT14_QUESTIONS)) return;

	function escapeHtml(s) {
		return String(s || '')
			.replace(/&/g, '&amp;')
			.replace(/</g, '&lt;')
			.replace(/>/g, '&gt;');
	}

	function superscriptsToHtml(s) {
		var t = String(s || '');
		var map = {
			'⁰': '0', '¹': '1', '²': '2', '³': '3', '⁴': '4', '⁵': '5', '⁶': '6', '⁷': '7', '⁸': '8', '⁹': '9',
			'⁺': '+', '⁻': '-'
		};
		return t.replace(/[⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻]+/g, function (m) {
			var inner = '';
			for (var i = 0; i < m.length; i++) inner += (map[m[i]] || m[i]);
			return '<sup>' + inner + '</sup>';
		});
	}

	function parseMatchParts(questionText, optionsFallback) {
		var q = String(questionText || '').replace(/\r/g, '');
		var lines = q.split(/\n/);
		var left = [];
		var seen = {};
		for (var i = 0; i < lines.length; i++) {
			var line = String(lines[i] || '').trim();
			var m = line.match(/^([АAБBВV])\)\s*(.+)$/);
			if (m) {
				var letter = m[1];
				if (letter === 'A') letter = 'А';
				if (letter === 'B') letter = 'Б';
				if (letter === 'V') letter = 'В';
				if (!seen[letter]) {
					seen[letter] = 1;
					left.push({ letter: letter, raw: m[2].trim() });
				}
			}
		}

		var right = [];
		var re = /(^|\n)\s*(\d+)\)\s*([^\n]+)/g;
		var mm;
		while ((mm = re.exec(q)) !== null) {
			right.push({ id: String(mm[2]), label: String(mm[3] || '').trim() });
		}
		if (!right.length && Array.isArray(optionsFallback)) {
			for (var j = 0; j < optionsFallback.length; j++) {
				right.push({ id: String(j + 1), label: String(optionsFallback[j]) });
			}
		}
		return { left: left, right: right };
	}

	function buildBodyHtml(questionText) {
		var full = String(questionText || '').replace(/\r/g, '');
		// Поддержка обоих вариантов: «СХЕМА ПРОЦЕССА:» и просто блоки А/Б/В.
		var intro = full.trim();
		// Оставляем всё, но красиво показываем верхний текст.
		return '<p style="white-space: pre-line;">' + escapeHtml(intro).replace(/\n/g, '<br/>') + '</p>';
	}

	function normalizeOne(src, idx) {
		var id = 140001 + idx;
		var parts = parseMatchParts(src.question, src.options);
		var rawAnswer = String(src.answer || '').replace(/\D/g, '');
		var correct = rawAnswer.split('').filter(Boolean);
		var matchLeft = parts.left.map(function (x) {
			return { letter: x.letter, label: superscriptsToHtml(escapeHtml(x.raw)) };
		});
		var matchRight = parts.right.map(function (x) {
			return { id: String(x.id), label: superscriptsToHtml(escapeHtml(x.label)) };
		});

		// fallback на input, если что-то не так (на всякий случай)
		if (matchLeft.length !== 3 || matchRight.length < 2 || correct.length !== 3) {
			return {
				id: id,
				type: 'input',
				title: 'Категория 14 · ОВР',
				body: buildBodyHtml(src.question),
				placeholder: 'например, 122',
				correct: rawAnswer,
				explanation: String(src.explanation || '')
			};
		}

		return {
			id: id,
			type: 'match',
			title: 'Категория 14 · ОВР',
			body: buildBodyHtml(src.question),
			matchLeft: matchLeft,
			matchRight: matchRight,
			correct: correct,
			explanation: String(src.explanation || '')
		};
	}

	var converted = IQMO_CAT14_QUESTIONS.map(normalizeOne);
	window.CHEMISTRY_QUESTIONS = window.CHEMISTRY_QUESTIONS || [];
	for (var k = 0; k < converted.length; k++) window.CHEMISTRY_QUESTIONS.push(converted[k]);
})();