// • Инертные газы: He, Ne, Ar, Kr, Xe (VIIIA)

if (typeof module !== 'undefined' && module.exports) {
  module.exports = IQMO_CAT05_QUESTIONS;
}

// Браузерный режим: конвертируем и добавляем в общий банк.
(function () {
	if (typeof window === 'undefined') return;
	if (!Array.isArray(IQMO_CAT05_QUESTIONS)) return;

	function isPick2(q) {
		// JS-regex \b не срабатывает на кириллице (см. cat01). Используем
		// безопасный lookahead на пробел/EOS.
		return /Какие\s+два\s+утверждения/i.test(q && q.question ? q.question : '')
			|| /Выберите\s+(два|две)(?=\s|$)/i.test(q && q.question ? q.question : '');
	}

	function toHtml(s) {
		return String(s || '')
			.replace(/&/g, '&amp;')
			.replace(/</g, '&lt;')
			.replace(/>/g, '&gt;');
	}

	function normalizeOne(src, idx) {
		// Категория 05: диапазон 50001–50064 (в файле 64 задания)
		var id = 50001 + idx;
		var pick2 = isPick2(src);
		var rawAnswer = String(src.answer || '');
		var options = Array.isArray(src.options)
			? src.options.map(function (label, i) {
					return { id: String(i + 1), label: String(label) };
				})
			: [];

		var out = {
			id: id,
			type: pick2 ? 'multi' : 'single',
			title: 'Категория 05 · Электронные оболочки',
			body: '<p>' + toHtml(src.question) + '</p>',
			options: options,
			explanation: String(src.explanation || '')
		};

		if (pick2) {
			out.pickCount = 2;
			out.correct = rawAnswer.split('').filter(Boolean);
		} else {
			out.correct = rawAnswer;
		}

		return out;
	}

	var converted = IQMO_CAT05_QUESTIONS.map(normalizeOne);
	window.CHEMISTRY_QUESTIONS = window.CHEMISTRY_QUESTIONS || [];
	for (var i = 0; i < converted.length; i++) window.CHEMISTRY_QUESTIONS.push(converted[i]);
})();
