	function parseReagentSets(question) {
		var q = String(question || '');
		var ix = q.search(/РЕАГЕНТЫ\s*:/i);
		if (ix === -1) return null;
		var tail = q.slice(ix).replace(/^РЕАГЕНТЫ\s*:\s*/i, '').trim();
		tail = tail.replace(/\.\s*$/, '').trim();
		var re = /(\d+)\)\s*([^;]+)/g;
		var sets = [];
		var m;
		while ((m = re.exec(tail)) !== null) {
			sets.push({ num: m[1], label: m[2].trim() });
		}
		if (sets.length < 3) return null;
		sets.sort(function (a, b) {
			return Number(a.num) - Number(b.num);
		});
		return sets.map(function (s) {
			return { id: String(s.num), label: s.label };
		});
	}

	function toHtml(s) {
		return String(s || '')
			.replace(/&/g, '&amp;')
			.replace(/</g, '&lt;')
			.replace(/>/g, '&gt;');
	}

	function normalizeOne(src, idx) {
		var id = 93001 + idx;
		var rawAnswer = String(src.answer || '').replace(/\D/g, '');
		var opts = Array.isArray(src.options) ? src.options : [];

		// Вариант 1: «соответствие» (А/Б/В → набор реагентов)
		if (opts.length === 3 && rawAnswer.length === 3) {
			var matchLeft = [
				{ letter: 'А', label: toHtml(opts[0] != null ? opts[0] : '') },
				{ letter: 'Б', label: toHtml(opts[1] != null ? opts[1] : '') },
				{ letter: 'В', label: toHtml(opts[2] != null ? opts[2] : '') }
			];
			var matchRight = parseReagentSets(src.question);
			var correct = rawAnswer.split('').filter(Boolean);
			if (matchRight && matchRight.length >= 3) {
				for (var j = 0; j < matchRight.length; j++) matchRight[j].label = toHtml(matchRight[j].label);
				return {
					id: id,
					type: 'match',
					title: 'Категория 09 · Свойства простых и сложных веществ',
					body: '<p>' + toHtml(src.question) + '</p>',
					matchLeft: matchLeft,
					matchRight: matchRight,
					correct: correct,
					explanation: String(src.explanation || '')
				};
			}
			// Если вдруг не распарсилось — fallback на input
			return {
				id: id,
				type: 'input',
				title: 'Категория 09 · Свойства простых и сложных веществ',
				body: '<p>' + toHtml(src.question) + '</p>',
				placeholder: 'например, 423',
				correct: String(src.answer || ''),
				explanation: String(src.explanation || '')
			};
		}

		// Вариант 2: «выбор 2 из 5» (авторские)
		if (opts.length === 5 && rawAnswer.length === 2) {
			var options = opts.map(function (label, i) {
				return { id: String(i + 1), label: toHtml(label) };
			});
			return {
				id: id,
				type: 'multi',
				pickCount: 2,
				title: 'Категория 09 · Свойства простых и сложных веществ',
				body: '<p style="white-space: pre-line;">' + toHtml(src.question).replace(/\n/g, '<br>') + '</p>',
				options: options,
				correct: rawAnswer.split('').filter(Boolean),
				explanation: String(src.explanation || '')
			};
		}

		// На всякий случай: общий fallback
		return {
			id: id,
			type: 'input',
			title: 'Категория 09 · Свойства простых и сложных веществ',
			body: '<p style="white-space: pre-line;">' + toHtml(src.question).replace(/\n/g, '<br>') + '</p>',
			placeholder: 'ответ',
			correct: String(src.answer || ''),
			explanation: String(src.explanation || '')
		};
	}

